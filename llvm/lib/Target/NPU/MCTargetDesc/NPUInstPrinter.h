#ifndef LLVM_LIB_TARGET_NPU_MCTARGETDESC_NPUINSTPRINTER_H
#define LLVM_LIB_TARGET_NPU_MCTARGETDESC_NPUINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class NPUInstPrinter : public MCInstPrinter {
public:
  NPUInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                 const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  // Print "offset(xN)" memory operands (used by load/store instructions).
  void printMemRIOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  // Print tile register number as "t<n>" (used by tensor engine instructions).
  void printTileOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_NPU_MCTARGETDESC_NPUINSTPRINTER_H
